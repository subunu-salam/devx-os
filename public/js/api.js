/* ---------- Toast ---------- */
export function toast(msg, type = '') {
  const root = document.getElementById('toast-root');
  const el = document.createElement('div');
  el.className = 'toast ' + (type === 'ok' ? 'ok' : type === 'err' ? 'err' : '');
  el.innerHTML = `${icon(type === 'err' ? 'x' : type === 'ok' ? 'check' : 'activity')}<span>${escapeHtml(msg)}</span>`;
  root.appendChild(el);
  setTimeout(() => { el.style.opacity = '0'; el.style.transition = '.3s'; setTimeout(() => el.remove(), 300); }, 2800);
}

/* ---------- Modal ---------- */
export function openModal({ title, body, size = '', footer = '', onMount }) {
  const root = document.getElementById('modal-root');
  const back = document.createElement('div');
  back.className = 'modal-back';
  back.innerHTML = `
    <div class="modal ${size}">
      <div class="modal-head"><h3>${escapeHtml(title)}</h3>
        <button class="btn btn-ghost btn-icon" data-close>${icon('x')}</button></div>
      <div class="modal-body">${body}</div>
      ${footer ? `<div class="modal-foot">${footer}</div>` : ''}
    </div>`;
  root.appendChild(back);
  const close = () => back.remove();
  back.addEventListener('click', (e) => { if (e.target === back || e.target.closest('[data-close]')) close(); });
  if (onMount) onMount(back, close);
  return { el: back, close };
}

export function confirmDialog(message, { danger = true, confirmText = 'Delete' } = {}) {
  return new Promise((resolve) => {
    const m = openModal({
      title: 'Please confirm',
      body: `<p style="color:var(--muted)">${escapeHtml(message)}</p>`,
      footer: `<button class="btn btn-outline" data-no>Cancel</button>
               <button class="btn ${danger ? 'btn-danger' : 'btn-primary'}" data-yes>${escapeHtml(confirmText)}</button>`,
      onMount: (back, close) => {
        back.querySelector('[data-no]').onclick = () => { close(); resolve(false); };
        back.querySelector('[data-yes]').onclick = () => { close(); resolve(true); };
      },
    });
  });
}

/* ---------- Small helpers ---------- */
export function optionList(values, selected) {
  return values.map((v) => `<option value="${escapeHtml(v)}"${v === selected ? ' selected' : ''}>${escapeHtml(v)}</option>`).join('');
}
export function debounce(fn, ms = 200) { let t; return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); }; }
